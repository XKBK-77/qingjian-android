    /**
     * 获取中文词的英文译词
     * @param word 中文词
     * @return 英文译词，如果没有则返回 null
     */
    fun translate(word: String): String? {
        // 先尝试整词匹配
        val direct = dict[word]
        if (direct != null) return direct

        // 如果是多字词，尝试逐字翻译后拼接（简化处理）
        if (word.length > 1) {
            val translations = mutableListOf<String>()
            for (ch in word) {
                val t = dict[ch.toString()]
                if (t != null) {
                    // 取第一个译词
                    translations.add(t.split("/")[0])
                } else {
                    return null
                }
            }
            if (translations.size == word.length) {
                return translations.joinToString(" ")
            }
        }

        return null
    }

    /**
     * 判断是否有该词的译词
     */
    fun hasTranslation(word: String): Boolean {
        return translate(word) != null
    }
