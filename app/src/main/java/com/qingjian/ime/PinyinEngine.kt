    // 将拼音字符串分割成单字拼音组合
    private fun splitPinyin(s: String): List<String> {
        // 递归分割，返回所有可能的单字组合的第一个候选拼接
        // 这里采用贪心+回溯
        val results = mutableListOf<String>()
        splitHelper(s, 0, mutableListOf(), results)
        return results.take(10)
    }

    private fun splitHelper(s: String, pos: Int, current: MutableList<String>, results: MutableList<String>) {
        if (pos == s.length) {
            // 拼接每个拼音的第一个候选字
            val sb = StringBuilder()
            for (py in current) {
                val words = dictionary[py]
                if (words != null && words.isNotEmpty()) {
                    sb.append(words[0])
                } else {
                    return // 某个拼音没有候选，放弃
                }
            }
            results.add(sb.toString())
            return
        }

        // 尝试1-6个字母的拼音
        for (len in 1..6) {
            if (pos + len > s.length) break
            val sub = s.substring(pos, pos + len)
            if (validPinyin.contains(sub) && dictionary.containsKey(sub)) {
                current.add(sub)
                splitHelper(s, pos + len, current, results)
                current.removeAt(current.size - 1)
                if (results.size >= 10) return
            }
        }
    }

    // 获取单个字的拼音（反向查询，用于译词）
    fun getPinyinOfChar(char: Char): String? {
        for ((py, words) in dictionary) {
            if (words.any { it.contains(char) }) {
                return py
            }
        }
        return null
    }
