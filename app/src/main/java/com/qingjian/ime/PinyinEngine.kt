    // 将输入的拼音分割成可能的单字拼音
    // 支持整词匹配
    fun getCandidates(pinyin: String): List<String> {
        if (pinyin.isEmpty()) return emptyList()

        val lower = pinyin.lowercase()

        // 先尝试整词匹配
        val exact = dictionary[lower]
        if (exact != null) {
            return exact
        }

        // 尝试前缀匹配（用户输入不完整，如 "niha" 匹配 "nihao"）
        val prefixMatches = mutableListOf<String>()
        for ((key, words) in dictionary) {
            if (key.startsWith(lower) && key.length > lower.length) {
                // 只取前几个候选
                prefixMatches.addAll(words.take(2))
            }
        }
        if (prefixMatches.isNotEmpty()) {
            return prefixMatches.distinct().take(20)
        }

        // 尝试分割成单字拼音
        val splitCandidates = splitPinyin(lower)
        if (splitCandidates.isNotEmpty()) {
            return splitCandidates
        }

        return emptyList()
    }

